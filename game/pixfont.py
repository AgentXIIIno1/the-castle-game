_cache = {}
def glyph(ch, col):
    k = (ch, col)
    if k not in _cache:
        rows = G.get(ch, G['?']).split()
        s = pygame.Surface((5, 7), pygame.SRCALPHA)
        for y, r in enumerate(rows):
            for x, b in enumerate(r):
                if b == '1': s.set_at((x, y), col)
        _cache[k] = s
    return _cache[k]

def width(text, scale=1): return len(text) * 6 * scale

def render(text, col, scale=1, shadow=(10, 6, 18)):
    text = text.upper()
    s = pygame.Surface((width(text, scale) + scale, 8*scale), pygame.SRCALPHA)
    for i, ch in enumerate(text):
        g = glyph(ch, col)
        if scale != 1: g = pygame.transform.scale(g, (5*scale, 7*scale))
        if shadow:
            sg = glyph(ch, shadow)
            if scale != 1: sg = pygame.transform.scale(sg, (5*scale, 7*scale))
            s.blit(sg, (i*6*scale + scale, scale))
        s.blit(g, (i*6*scale, 0))
    return s
